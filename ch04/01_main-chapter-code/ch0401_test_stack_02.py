import torch

# ==========================================
# 构造一个 batch（批次）
# ==========================================
# 这里创建了两个一维 Tensor，每个 Tensor 有 4 个元素。
#
# 第一个样本：
# [6109, 3626, 6100, 345]
#
# 第二个样本：
# [6109, 1110, 6622, 257]
#
# 可以把它理解成：
# batch 中有两个句子，每个句子长度都是 4。
batch = [
    torch.tensor([6109, 3626, 6100, 345]),
    torch.tensor([6109, 1110, 6622, 257])
]

# 打印原始 batch
# print(batch)

# ====================================================
# torch.stack(dim=0)
# ====================================================
# stack()：把多个 Tensor 沿着新的维度拼接。
#
# 注意：
# stack() 会"新增一个维度"。
#
# 原来每个 Tensor 的形状：
# (4,)
#
# stack(dim=0) 后：
# (2,4)
#
# 新增的维度放在最前面（第0维）。
#
# 可以理解成：
#
#      第0维（batch）
#          ↓
# [
#   [6109, 3626, 6100, 345],
#   [6109, 1110, 6622, 257]
# ]
#
# 一共2个样本，每个样本4个元素。
batch0 = torch.stack(batch, dim=0)

print(batch0)

# 输出形状
print(batch0.shape)
# torch.Size([2, 4])

print("-" * 50)

# ====================================================
# torch.stack(dim=1)
# ====================================================
# 这里仍然会新增一个维度，
# 但是新增的位置是在第1维。
#
# 原始两个 Tensor：
#
# tensor1:
# [6109, 3626, 6100, 345]
#
# tensor2:
# [6109, 1110, 6622, 257]
#
# stack(dim=1) 后，会变成：
#
# [
#   [6109, 6109],
#   [3626, 1110],
#   [6100, 6622],
#   [ 345,  257]
# ]
#
# 可以理解成：
#
# 第0维：原来Tensor中的位置（长度4）
# 第1维：来自不同Tensor的数据（2个Tensor）
#
# 所以形状变成：
# (4,2)
batch1 = torch.stack(batch, dim=1)

print(batch1)

# 输出形状
print(batch1.shape)
# torch.Size([4, 2])